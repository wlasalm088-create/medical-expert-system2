% =================================================================
% نظام خبير طبي تفاعلي لتشخيص الأمراض التنفسية

% =================================================================

% -----------------------------------------------------------------
% 1. قاعدة البيانات الديناميكية (Dynamic Database)
% تتيح للنظام تخزين الإجابات مؤقتاً أثناء الجلسة حتى لا يسأل المريض نفس السؤال مرتين
% -----------------------------------------------------------------
:- dynamic(answered/2).

% -----------------------------------------------------------------
% 2. محرك الاستعلام والتفاعل (Interaction Engine)
% دالة ask تقوم بسؤال المستخدم والتأكد من إجابته، ثم تخزينها
% -----------------------------------------------------------------
ask(Symptom) :-
    answered(Symptom, Response), !, % إذا سُئل السؤال سابقاً، استخدم الإجابة المخزنة
    Response == yes.

ask(Symptom) :-
    format("هل تعاني من ~w؟ (نعم./لا.): ", [Symptom]),
    read(Input),
    ( (Input == yes ; Input == 'نعم') -> Response = yes ; Response = no ),
    asserta(answered(Symptom, Response)), % تخزين الإجابة في الذاكرة المؤقتة
    Response == yes.

% -----------------------------------------------------------------
% 3. قواعد التشخيص (Diagnostic Rules)
% تمثل المعرفة الطبية (Knowledge Base) للتمييز بين الأمراض
% -----------------------------------------------------------------
:- dynamic(answered/2).

clear :-
    retractall(answered(_, _)).

diagnosis(covid19) :-
    answered(fever, yes),
    answered(cough, yes),
    answered(breath, yes).

diagnosis(flu) :-
    answered(fever, yes),
    answered(cough, yes),
    answered(breath, no).

diagnosis(common_cold) :-
    answered(cough, yes),
    answered(fever, no),
    answered(breath, no).


% -----------------------------------------------------------------
% 4. واجهة التشغيل والتحكم (Control Logic)
% الدالة الرئيسية التي يبدأ منها البرنامج
% -----------------------------------------------------------------
start :-
    retractall(answered(_, _)), % مسح ذاكرة الإجابات السابقة لبدء جلسة جديدة
    write('-------------------------------------------'), nl,
    write('   مرحباً بك في نظام التشخيص الطبي الذكي   '), nl,
    write('-------------------------------------------'), nl,
    ( diagnosis(Disease) ->
        format("التشخيص المقترح هو: ~w", [Disease])
    ;
        write('عذراً، لم يتمكن النظام من تحديد المرض بدقة بناءً على الأعراض.')
    ),
    nl, write('نتمنى لك الشفاء العاجل.'), nl.

